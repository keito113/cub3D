#include "libft.h" // "libft.h"を読み込み、必要な型・定数・関数宣言を参照可能にする

/* 関数概要: ft_atoi - 文字列を整数へ変換する。引数(const char *nptr)を受け取り、成功/失敗または計算結果を戻り値で返す。 */
int	ft_atoi(const char *nptr) // ft_atoi関数のシグネチャを定義し、ここから本体処理を記述する
{ // ここからブロックスコープを開始する
	int	i; // 変数 i（ループ用インデックス） を宣言する
	int	sign; // 変数 sign（signの作業用値） を宣言する
	int	num; // 変数 num（numの作業用値） を宣言する

	i = 0; // i に 0 の計算結果を代入する
	sign = 1; // sign に 1 の計算結果を代入する
	num = 0; // num に 0 の計算結果を代入する
	while ((nptr[i] >= 9 && nptr[i] <= 13) || nptr[i] == 32) // (nptr[i] >= 9 が成立する かつ nptr[i] <= 13) が成立する または nptr[i] == 32 が成立する場合に分岐する
	{ // ここからブロックスコープを開始する
		i++; // 文 `i++;` を実行する
	} // ここでブロックスコープを終了する
	if (nptr[i] == '-' || nptr[i] == '+') // nptr[i] == '-' が成立する または nptr[i] == '+' が成立する場合に分岐する
	{ // ここからブロックスコープを開始する
		if (nptr[i] == '-') // nptr[i] == '-' が成立する場合に分岐する
			sign = sign * (-1); // sign に sign * (-1) の計算結果を代入する
		i++; // 文 `i++;` を実行する
	} // ここでブロックスコープを終了する
	while ('0' <= nptr[i] && nptr[i] <= '9') // '0' <= nptr[i] が成立する かつ nptr[i] <= '9' が成立する場合に分岐する
	{ // ここからブロックスコープを開始する
		num = num * 10 + (nptr[i] - '0'); // num に num * 10 + (nptr[i] - '0') の計算結果を代入する
		i++; // 文 `i++;` を実行する
	} // ここでブロックスコープを終了する
	return (num * sign); // 関数を終了し、num * sign を呼び出し元へ返す
} // ここでブロックスコープを終了する

