/* 関数概要: ft_isdigit - 数字か判定する。引数(int c)を受け取り、成功/失敗または計算結果を戻り値で返す。 */
int	ft_isdigit(int c) // ft_isdigit関数のシグネチャを定義し、ここから本体処理を記述する
{ // ここからブロックスコープを開始する
	if (('0' <= c && c <= '9')) // ('0' <= c が成立する かつ c <= '9') が成立する場合に分岐する
	{ // ここからブロックスコープを開始する
		return (1); // 関数を終了し、1 を呼び出し元へ返す
	} // ここでブロックスコープを終了する
	else // 直前のif/else if条件に当てはまらない場合の処理へ進む
	{ // ここからブロックスコープを開始する
		return (0); // 関数を終了し、0 を呼び出し元へ返す
	} // ここでブロックスコープを終了する
} // ここでブロックスコープを終了する

