/* 関数概要: ft_isprint - 表示可能文字か判定する。引数(int c)を受け取り、成功/失敗または計算結果を戻り値で返す。 */
int	ft_isprint(int c) // ft_isprint関数のシグネチャを定義し、ここから本体処理を記述する
{ // ここからブロックスコープを開始する
	if (32 <= c && c <= 126) // 32 <= c が成立する かつ c <= 126 が成立する場合に分岐する
	{ // ここからブロックスコープを開始する
		return (1); // 関数を終了し、1 を呼び出し元へ返す
	} // ここでブロックスコープを終了する
	else // 直前のif/else if条件に当てはまらない場合の処理へ進む
	{ // ここからブロックスコープを開始する
		return (0); // 関数を終了し、0 を呼び出し元へ返す
	} // ここでブロックスコープを終了する
} // ここでブロックスコープを終了する

