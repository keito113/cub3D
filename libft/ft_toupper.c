/* 関数概要: ft_toupper - 小文字を大文字へ変換する。引数(int c)を受け取り、成功/失敗または計算結果を戻り値で返す。 */
int	ft_toupper(int c) // ft_toupper関数のシグネチャを定義し、ここから本体処理を記述する
{ // ここからブロックスコープを開始する
	if ('a' <= c && c <= 'z') // 'a' <= c が成立する かつ c <= 'z' が成立する場合に分岐する
	{ // ここからブロックスコープを開始する
		return (c - 32); // 関数を終了し、c - 32 を呼び出し元へ返す
	} // ここでブロックスコープを終了する
	else // 直前のif/else if条件に当てはまらない場合の処理へ進む
	{ // ここからブロックスコープを開始する
		return (c); // 関数を終了し、c を呼び出し元へ返す
	} // ここでブロックスコープを終了する
} // ここでブロックスコープを終了する

