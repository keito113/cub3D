#include "libft.h" // "libft.h"を読み込み、必要な型・定数・関数宣言を参照可能にする

/* 関数概要: ft_putnbr_fd - 整数をファイルディスクリプタへ出力する。引数(int n, int fd)を受け取り、必要な状態更新を反映して呼び出し元へ戻る。 主な内部呼び出し: write() -> ft_putchar_fd()。 */
void	ft_putnbr_fd(int n, int fd) // ft_putnbr_fd関数のシグネチャを定義し、ここから本体処理を記述する
{ // ここからブロックスコープを開始する
	if (n == -2147483648) // n == -2147483648 が成立する場合に分岐する
	{ // ここからブロックスコープを開始する
		write(fd, "-2147483648", 11); // write() を呼び出して、writeを実行する
		return ; // この時点で関数を終了して呼び出し元へ戻る
	} // ここでブロックスコープを終了する
	if (n < 0) // n < 0 が成立する場合に分岐する
	{ // ここからブロックスコープを開始する
		ft_putchar_fd('-', fd); // ft_putchar_fd() を呼び出して、1文字をファイルディスクリプタへ出力する
		n = -n; // n に -n の計算結果を代入する
	} // ここでブロックスコープを終了する
	if (n >= 10) // n >= 10 が成立する場合に分岐する
		ft_putnbr_fd(n / 10, fd); // ft_putnbr_fd() を呼び出して、整数をファイルディスクリプタへ出力する
	ft_putchar_fd(n % 10 + '0', fd); // ft_putchar_fd() を呼び出して、1文字をファイルディスクリプタへ出力する
} // ここでブロックスコープを終了する

