#include "libft.h" // "libft.h"を読み込み、必要な型・定数・関数宣言を参照可能にする

/* 関数概要: ft_max - 2値の大きい方を返す。引数(int a, int b)を受け取り、成功/失敗または計算結果を戻り値で返す。 */
int	ft_max(int a, int b) // ft_max関数のシグネチャを定義し、ここから本体処理を記述する
{ // ここからブロックスコープを開始する
	if (a > b) // a > b が成立する場合に分岐する
		return (a); // 関数を終了し、a を呼び出し元へ返す
	return (b); // 関数を終了し、b を呼び出し元へ返す
} // ここでブロックスコープを終了する
