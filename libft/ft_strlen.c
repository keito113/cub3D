#include "libft.h" // "libft.h"を読み込み、必要な型・定数・関数宣言を参照可能にする

/* 関数概要: ft_strlen - 文字列長を取得する。引数(const char *str)を受け取り、成功/失敗または計算結果を戻り値で返す。 */
size_t	ft_strlen(const char *str) // ft_strlen関数のシグネチャを定義し、ここから本体処理を記述する
{ // ここからブロックスコープを開始する
	size_t	i; // 変数 i（ループ用インデックス） を宣言する

	i = 0; // i に 0 の計算結果を代入する
	while (str[i] != '\0') // str[i] != '\0' が成立する場合に分岐する
	{ // ここからブロックスコープを開始する
		i++; // 文 `i++;` を実行する
	} // ここでブロックスコープを終了する
	return (i); // 関数を終了し、i を呼び出し元へ返す
} // ここでブロックスコープを終了する

