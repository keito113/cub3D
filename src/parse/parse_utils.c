#include "cub3d.h" // "cub3d.h"を読み込み、必要な型・定数・関数宣言を参照可能にする

/* 関数概要: skip_space - 文字列先頭の空白を読み飛ばした位置を返す。引数(char *str)を受け取り、成功/失敗または計算結果を戻り値で返す。 */
char	*skip_space(char *str) // skip_space関数のシグネチャを定義し、ここから本体処理を記述する
{ // ここからブロックスコープを開始する
	while (*str == ' ' || *str == '\t') // *str == ' ' が成立する または *str == '\t' が成立する場合に分岐する
		str++; // 文 `str++;` を実行する
	return (str); // 関数を終了し、str を呼び出し元へ返す
} // ここでブロックスコープを終了する

/* 関数概要: free_split - splitを解放する。引数(char **vec)を受け取り、必要な状態更新を反映して呼び出し元へ戻る。 主な内部呼び出し: free()。 */
void	free_split(char **vec) // free_split関数のシグネチャを定義し、ここから本体処理を記述する
{ // ここからブロックスコープを開始する
	int	i; // 変数 i（ループ用インデックス） を宣言する

	if (!vec) // 条件(!vec)が成立する場合に分岐する
		return ; // この時点で関数を終了して呼び出し元へ戻る
	i = 0; // i に 0 の計算結果を代入する
	while (vec[i]) // 条件(vec[i])が成立する場合に分岐する
	{ // ここからブロックスコープを開始する
		free(vec[i]); // free() を呼び出して、対象を解放する
		i++; // 文 `i++;` を実行する
	} // ここでブロックスコープを終了する
	free(vec); // free() を呼び出して、対象を解放する
} // ここでブロックスコープを終了する
